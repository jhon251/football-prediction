"""Mock Data Provider.

Serves the SYNTHETIC fixture set under ``data/fixtures/`` (generated by
``scripts/generate_fixtures.py``).  No real football statistics are used and
no value is ever fabricated on demand: missing data is returned as
None / empty / ``unknown`` so the Data Quality layer can react.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional

from football_simulation.data.provider import DataProvider
from football_simulation.models.data import (
    ActualMatchResult,
    DataQualityInfo,
    MatchHistory,
    MatchHistoryEntry,
    OddsData,
    WeatherData,
)
from football_simulation.models.entities import (
    CoachProfile,
    Competition,
    FixtureLineup,
    InjuryRecord,
    MatchRequest,
    PlayerProfile,
    RefereeProfile,
    TeamProfile,
)
from football_simulation.models.events import MatchEvent


class MockDataProvider(DataProvider):
    """In-memory provider over JSON fixtures (development / testing)."""

    name = "mock"

    def __init__(self, fixtures_dir: Optional[Path] = None):
        if fixtures_dir is None:
            fixtures_dir = Path(__file__).resolve().parent / "fixtures"
        self._dir = fixtures_dir
        self._teams: Dict[str, TeamProfile] = {}
        self._players: Dict[str, List[PlayerProfile]] = {}
        self._coaches: Dict[str, CoachProfile] = {}
        self._referees: Dict[str, RefereeProfile] = {}
        self._lineups: Dict[str, Dict[str, FixtureLineup]] = {}  # match_id -> team_id -> lineup
        self._injuries: Dict[str, List[InjuryRecord]] = {}  # team_id -> records
        self._histories: Dict[str, MatchHistory] = {}
        self._weather: Dict[str, WeatherData] = {}
        self._odds: Dict[str, OddsData] = {}
        self._requests: Dict[str, MatchRequest] = {}
        self._referee_appointments: Dict[str, str] = {}
        self._results: Dict[str, ActualMatchResult] = {}
        self._load()

    # ------------------------------------------------------------------
    def _load(self) -> None:
        def read(name: str):
            path = self._dir / name
            if not path.exists():
                raise FileNotFoundError(
                    f"Fixture {path} missing - run scripts/generate_fixtures.py first."
                )
            return json.loads(path.read_text(encoding="utf-8"))

        teams = read("teams.json")
        for item in teams["teams"]:
            tp = TeamProfile.model_validate(item)
            self._teams[tp.team_id] = tp

        players = read("players.json")
        for item in players["players"]:
            pp = PlayerProfile.model_validate(item)
            self._players.setdefault(pp.team_id, []).append(pp)

        coaches = read("coaches.json")
        for item in coaches["coaches"]:
            cp = CoachProfile.model_validate(item)
            self._coaches[cp.coach_id] = cp

        referees = read("referees.json")
        for item in referees["referees"]:
            rp = RefereeProfile.model_validate(item)
            self._referees[rp.referee_id] = rp

        lineups = read("lineups.json")
        for item in lineups["lineups"]:
            fl = FixtureLineup.model_validate(item)
            self._lineups.setdefault(item["match_id"], {})[fl.team_id] = fl

        injuries = read("injuries.json")
        for item in injuries["injuries"]:
            ir = InjuryRecord.model_validate(item)
            self._injuries.setdefault(ir.team_id, []).append(ir)

        histories = read("history.json")
        for item in histories["histories"]:
            entries = [MatchHistoryEntry.model_validate(e) for e in item["entries"]]
            mh = MatchHistory(
                team_id=item["team_id"],
                competition_id=item.get("competition_id", ""),
                season=item.get("season", ""),
                entries=entries,
                complete=item.get("complete", True),
            )
            self._histories[item["team_id"]] = mh

        weather = read("weather.json")
        for item in weather["weather"]:
            self._weather[item["match_id"]] = WeatherData.model_validate(item)

        odds = read("odds.json")
        for item in odds["odds"]:
            self._odds[item["match_id"]] = OddsData.model_validate(item)

        matches = read("matches.json")
        for item in matches["matches"]:
            req = MatchRequest.model_validate(item["request"])
            self._requests[req.match_id] = req
            if item.get("referee_id"):
                self._referee_appointments[req.match_id] = item["referee_id"]

        results = read("results.json")
        for item in results["results"]:
            res = ActualMatchResult.model_validate(item)
            self._results[res.match_id] = res

    # ------------------------------------------------------------------
    # DataProvider implementation
    # ------------------------------------------------------------------
    def get_competition_info(self, competition_id: str) -> Competition:
        # Competition registry lives in the same package; import lazily to
        # avoid a hard dependency cycle.
        from football_simulation.data.registry import load_registry_from_package

        return load_registry_from_package().competition(competition_id)

    def get_team_data(self, team_id: str) -> TeamProfile:
        if team_id not in self._teams:
            raise KeyError(f"Unknown team: {team_id!r}")
        return self._teams[team_id]

    def get_player_data(self, team_id: str) -> List[PlayerProfile]:
        return list(self._players.get(team_id, []))

    def get_coach_data(self, coach_id: str) -> CoachProfile:
        if coach_id not in self._coaches:
            raise KeyError(f"Unknown coach: {coach_id!r}")
        return self._coaches[coach_id]

    def get_match_history(
        self, team_id: str, competition_id: str, season: str, before: datetime
    ) -> MatchHistory:
        history = self._histories.get(team_id)
        if history is None:
            return MatchHistory(team_id=team_id, competition_id=competition_id, season=season)
        kept = [e for e in history.entries if e.date < before]
        return history.model_copy(
            update={
                "entries": kept,
                "competition_id": competition_id or history.competition_id,
                "season": season or history.season,
                "complete": len(kept) == len(history.entries),
            }
        )

    def get_lineup(self, team_id: str, match_id: str) -> Optional[FixtureLineup]:
        return self._lineups.get(match_id, {}).get(team_id)

    def get_injury(self, team_id: str, before: datetime) -> List[InjuryRecord]:
        records = [r for r in self._injuries.get(team_id, []) if r.known_at is None or r.known_at <= before]
        # Only current injuries (not yet returned).
        active = [
            r
            for r in records
            if r.expected_return is None or r.expected_return >= before
        ]
        return active

    def get_referee_data(self, referee_id: str) -> RefereeProfile:
        if referee_id not in self._referees:
            raise KeyError(f"Unknown referee: {referee_id!r}")
        return self._referees[referee_id]

    def get_weather(self, match_id: str, venue: str) -> WeatherData:
        return self._weather.get(match_id, WeatherData(match_id=match_id, venue=venue, known=False))

    def get_odds(self, match_id: str) -> Optional[OddsData]:
        return self._odds.get(match_id)

    def get_event_data(self, match_id: str) -> List[MatchEvent]:
        result = self._results.get(match_id)
        if result is None:
            return []
        return [MatchEvent.model_validate(e) for e in result.events]

    def get_match_result(self, match_id: str) -> Optional[ActualMatchResult]:
        return self._results.get(match_id)

    def get_match_request(self, match_id: str) -> MatchRequest:
        if match_id not in self._requests:
            raise KeyError(f"Unknown match: {match_id!r}")
        return self._requests[match_id]

    def referee_for_match(self, match_id: str) -> Optional[str]:
        return self._referee_appointments.get(match_id)

    def data_quality(self, request: MatchRequest) -> DataQualityInfo:
        unknowns: List[str] = []
        lineups: Dict[str, bool] = {}
        for team_id in (request.home_team_id, request.away_team_id):
            lineup = self.get_lineup(team_id, request.match_id)
            confirmed = bool(lineup and lineup.confirmed)
            lineups[team_id] = confirmed
            if not confirmed:
                unknowns.append(f"lineup_{team_id}")
        weather = self.get_weather(request.match_id, request.venue)
        if not weather.known:
            unknowns.append("weather")
        referee = self.referee_for_match(request.match_id)
        if referee is None:
            unknowns.append("referee")
        else:
            rp = self.get_referee_data(referee)
            if rp.matches_officiated < 10:
                unknowns.append("referee_sample_small")
        for team_id in (request.home_team_id, request.away_team_id):
            history = self._histories.get(team_id)
            if history is None or len(history.entries) < 5:
                unknowns.append(f"history_short_{team_id}")
            players = self._players.get(team_id, [])
            if len(players) < 16:
                unknowns.append(f"squad_short_{team_id}")
        total_slots = 2 + 2 + 1 + 1  # lineups, histories, weather, referee
        completeness = max(0.0, 1.0 - len(unknowns) / (total_slots + 2))
        notes = ["Mock provider: all values are synthetic development fixtures."]
        return DataQualityInfo(
            completeness=round(completeness, 3),
            unknowns=unknowns,
            lineup_confirmed=lineups,
            notes=notes,
        )
